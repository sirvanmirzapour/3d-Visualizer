  static String tr(AppLocale locale, String key, [Map<String, String>? args]) {
    final Map<String, String> table;
    switch (locale) {
      case AppLocale.fa:
        table = fa;
        break;
      case AppLocale.ku:
        table = ku;
        break;
      case AppLocale.ar:
        table = ar;
        break;
      case AppLocale.de:
        table = de;
        break;
      case AppLocale.en:
        table = en;
        break;
    }
    var text = table[key] ?? en[key] ?? key;
    args?.forEach((k, v) {
      text = text.replaceAll('{$k}', v);
    });
    return text;
  }

